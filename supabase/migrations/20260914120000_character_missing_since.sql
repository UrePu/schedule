-- ═══════════════════════════════════════════════════════════════════════════════
-- M_Schedule · 캐릭터 목록에서 **사라진 캐릭터**를 사라졌다고 말하기
-- ═══════════════════════════════════════════════════════════════════════════════
--
-- 발주 보고(2026-09-14): *"킴잔아델 < 리프하고 캐릭터가 사라졌다고함. 추적 캐릭터도
-- 새로고침 하는거 필요함."* (리프 = **월드 리프**, 캐릭터를 다른 월드로 이전하는 시스템)
--
-- ───────────────────────────────────────────────────────────────────────────────
-- 월드 리프가 우리 데이터에 하는 일
-- ───────────────────────────────────────────────────────────────────────────────
-- 리프는 **ocid 와 world_name 을 둘 다** 바꾼다. `syncCredentialInventory` 는 행을 찾을 때
--   ① ocid → ② (이름, 월드) 순으로 보는데(§1.1 — ocid 는 가변이라 PK 가 아니다),
-- 리프한 캐릭터는 **두 조회가 모두 빗나간다.** 그래서 새 행이 생기고, 옛 행은 아무도
-- 갱신하지 않는 **유령**으로 남는다. 화면이 "캐릭터가 사라졌다"고 보이는 것이 그 유령이다.
--
-- ★ **옛 행과 새 행을 추측으로 잇지 않는다.** 잇는 근거가 될 만한 값이 하나도 남지 않기
--   때문이다(ocid 도 월드도 바뀌었고, 이름은 개명으로 또 바뀔 수 있다). 잘못 이으면 남의
--   클리어·수익 기록이 엉뚱한 캐릭터에 붙는다 — 되돌릴 수 없는 종류의 사고다.
--   그래서 이 마이그레이션이 하는 일은 하나뿐이다: **유령을 유령이라고 표시한다.**
--
-- ───────────────────────────────────────────────────────────────────────────────
-- ★★ 왜 지우지 않는가 ★★
-- ───────────────────────────────────────────────────────────────────────────────
-- `characters.id` 에는 과거가 통째로 매달려 있다:
--   · `boss_clears.character_id`                → 그 캐릭터가 깬 결정석 = **수익 원장**
--   · `run_signups.character_id`               → 어느 캐릭터로 그 런에 갔는가
--   · `character_boss_plans.character_id`      → 캐릭별 주간 보스 계획
--   · `character_scheduler_snapshots.character_id` → 넥슨 미러
--   · `party_participants.character_id`        → 파티 구성원이 데려가는 캐릭터
-- 행을 지우면 **지난 주차의 수익이 끊긴다.** 사라진 캐릭터는 "없는 것"이 아니라
-- **"이제 넥슨에서 못 보는 것"** 이고, 벌어 둔 메소는 여전히 벌어 둔 것이다.
-- 그래서 삭제가 아니라 **시각 한 칸**이다. 다시 나타나면 이 칸을 null 로 되돌리면 끝이고,
-- 그 사이의 기록은 한 줄도 손대지 않는다.
--
-- ───────────────────────────────────────────────────────────────────────────────
-- 이 칸이 실제로 무엇을 막는가 — **매시간 나가던 헛 호출**
-- ───────────────────────────────────────────────────────────────────────────────
-- 스케줄러 동기화는 `is_tracked = true` 인 캐릭터를 **캐릭터당 1콜**로 돈다(§2.1.1).
-- 리프·삭제로 사라진 캐릭터는 그 호출이 영원히 실패하는데, 크론은 매시 :50 에 돈다
-- (§1.1.1). 즉 유령 하나가 **하루 24콜**을 태운다(개발 키는 하루 1,000콜).
-- 동기화 대상 선정이 이 칸을 함께 보게 되면서 그 소비가 0이 된다.
-- ═══════════════════════════════════════════════════════════════════════════════


-- #############################################################################
-- 1. 칸
-- #############################################################################

alter table public.characters
  add column if not exists missing_since timestamptz;

comment on column public.characters.missing_since is
  '이 캐릭터가 넥슨 /character/list 에서 **처음 보이지 않게 된 시각**. '
  'null = 마지막 새로고침에 있었다(정상). 월드 리프·캐릭터 삭제·키 회수가 원인이며 '
  '셋을 구분할 방법이 API 에 없다. **오류 기록이 아니라 상태 기록**이다. '
  '행을 지우지 않는 이유: boss_clears·run_signups·character_boss_plans 가 이 id 에 '
  '매달려 있어 지우면 과거 수익이 끊긴다. 다시 보이면 null 로 되돌린다(덮어쓰지 않는다 — '
  '"언제부터 안 보였나"가 이 칸의 값이다). 동기화 대상 선정은 반드시 이 칸을 함께 봐야 '
  '한다. 보지 않으면 사라진 캐릭터 하나가 매시 크론에서 하루 24콜을 헛되이 태운다.';

/*
  ★ **인덱스를 두지 않는다.** 이 칸을 읽는 자리는 둘뿐이고 둘 다 인덱스가 의미 없다.
      · 동기화 대상 선정 — `is_tracked = true and missing_since is null`. 실측 전체 행이
        651행이고 그중 추적은 수십 행이라, 계획기는 어차피 순차 스캔을 고른다.
      · 선택 모달의 목록 — 애초에 그 사용자의 전 캐릭터를 다 읽는다(필터가 아니다).
    "언젠가 쓸지 모른다"로 인덱스를 심으면 쓰기마다 비용만 늘고, 그 비용을 내는 쪽은
    매시 도는 동기화의 UPDATE 다. 필요해지면 그때 계획을 보고 만든다.
*/


-- #############################################################################
-- 2. 권한 — **테이블 단위 GRANT 를 새로 쓰지 않는다**
-- #############################################################################
--
-- `public.characters` 는 마이그레이션 08 이 정한 **비공개 19표** 중 하나다:
--     revoke all ... from anon;  revoke all ... from authenticated;
--     grant  all  on table public.characters to service_role;
-- 즉 anon·authenticated 에게는 **컬럼 권한이 애초에 하나도 없고**, 새 칸이 붙어도 열릴
-- 자리가 없다. `character_looks`(마이그레이션 20260903120000)처럼 컬럼 단위 GRANT 를
-- 다시 쓰는 것은 **읽기가 공개인 표**의 이야기이고, 여기서 그걸 흉내 내면 지금 닫혀 있는
-- 표에 오히려 문을 내는 꼴이 된다.
--
-- service_role 쪽은 **테이블 단위 GRANT 가 새 컬럼을 자동으로 포함**하므로 추가 부여도
-- 필요 없다. (그 자동 포함이 공개 표에서는 사고의 원인이지만, 여기서는 대상이
-- service_role 하나뿐이라 위험이 없다 — 문제는 "누구에게" 열리느냐였다.)
--
-- → 그래서 이 절은 **아무 권한도 바꾸지 않는다.** 대신 아래에서 실제로 그러한지 확인한다.


-- #############################################################################
-- 3. 자기검증 — 확인하지 않은 가정은 남기지 않는다
-- #############################################################################

do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'characters'
      and column_name = 'missing_since'
  ) then
    raise exception 'characters.missing_since 가 만들어지지 않았습니다.';
  end if;

  -- 위 2절의 주장("anon/authenticated 에는 열릴 자리가 없다")을 말로 두지 않고 검사한다.
  if has_column_privilege('anon', 'public.characters', 'missing_since', 'SELECT')
     or has_column_privilege('authenticated', 'public.characters', 'missing_since', 'SELECT')
  then
    raise exception 'characters.missing_since 가 anon/authenticated 에게 노출되었습니다.';
  end if;

  -- 새 칸을 실제로 쓰는 것은 서버뿐이다. 그 권한이 없으면 새로고침이 조용히 실패한다.
  if not has_column_privilege('service_role', 'public.characters', 'missing_since', 'UPDATE')
  then
    raise exception 'service_role 이 characters.missing_since 를 쓸 수 없습니다.';
  end if;

  -- RLS 는 08 에서 이미 켰다. 꺼져 있으면 이 칸과 무관하게 더 큰 문제다.
  if (select relrowsecurity from pg_class where oid = 'public.characters'::regclass) is not true
  then
    raise exception 'characters 에 RLS 가 켜져 있지 않습니다.';
  end if;

  raise notice 'characters.missing_since 추가 완료 — 비공개 유지, service_role 전용 쓰기';
end $$;

select public.assert_no_public_sensitive_columns();
