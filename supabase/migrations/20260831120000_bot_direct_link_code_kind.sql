-- ═══════════════════════════════════════════════════════════════════════════════
-- M_Schedule · `bot_link_code_kind` 에 `direct_pair` 한 값을 더한다
-- ═══════════════════════════════════════════════════════════════════════════════
--
-- ⚠️ **이 파일이 따로 존재하는 이유는 문법 제약 하나뿐이다.**
--    PostgreSQL 에서 `alter type ... add value` 로 더한 이넘 값은 **그 트랜잭션 안에서
--    쓸 수 없다**(`unsafe use of new value of enum type`). 마이그레이션은 파일 하나가
--    트랜잭션 하나이므로, 같은 파일에서 값을 더하고 그 값으로 검증·시드를 하면 그 자리에서
--    깨진다. 그래서 **값을 더하는 일만** 이 파일이 하고, 그 값을 실제로 쓰는 코드는
--    바로 다음 파일(`..._bot_direct_notifications.sql`)이 갖는다.
--    두 파일을 합치려는 다음 사람에게: 합치면 반드시 깨진다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 새 테이블이 아니라 기존 축인가
-- ─────────────────────────────────────────────────────────────────────────────
-- `bot_link_codes` 는 이미 "무엇을 여는 코드인가"를 `kind` 로 가르고 있다
-- (`channel_pair` = 방을 서버에 붙인다 · `member_link` = 방에서 내가 나임을 밝힌다).
-- 개인톡 방도 결국 **방을 하나 붙이는 일**이라 같은 축에 속하며, 다른 것은 단 하나
-- — 그렇게 열린 채널이 `bot_channels.kind = 'direct'` 가 된다는 점이다.
-- 코드 발급·소모·폐기·TTL·시도 제한이 전부 그대로 재사용된다.

alter type public.bot_link_code_kind add value if not exists 'direct_pair';

