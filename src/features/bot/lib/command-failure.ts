/**
 * 명령이 서버 안에서 실패하거나 상한을 넘겼을 때 방에 나가는 **오류 답장**.
 *
 * 발주 지시(2026-11-02): *"DB가 멈춰서 이슈가 생기면. 오류생겼다고 답장을 대신해"*.
 *
 * ★ 문구가 둘인 이유는 **다시 치는 것이 위험한 명령이 있어서**다. 답을 못 받았다고 해서 처리가
 *   안 된 것은 아니고, `!드랍` 은 재전송으로 두 번 기록된 적이 있다(`scripts/OpenchatbotR.js`
 *   `COMMAND_TIMEOUT` 주석). 그런 명령에 "다시 치세요"만 말하면 사람이 같은 사고를 낸다.
 *
 * ⚠️ 내부 사정(오류 코드 · DB · 시간 초과)은 절대 말하지 않는다. 사용자가 할 일만 말한다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 분류 기준 — 기준은 "평소 답이 나가는 입력인가"다
 * ─────────────────────────────────────────────────────────────────────────────
 *   1. **미인식** — 아는 명령도 오타 제안 대상도 아닌 것(`!ㅋㅋ`). 평소 침묵하므로 **장애 중에도
 *      침묵한다.** 최근 30일 명령의 20%(158/784)가 여기라, 문구를 내면 장애 때 방 전체 잡담에
 *      "처리됐을 수도 있으니…" 가 나간다. 판정은 `isAnsweredCommand`, 응답은 라우트가 한다.
 *   2. **오타 제안 대상**(`!결정` → `!일정`, 같은 기간 53건) — 평소 답이 나가므로 인식된 것으로 친다.
 *      아래 목록에 없으니 쓰기 문구다.
 *   3. **아는 명령** — 아래 목록에 있으면 읽기 문구, 없으면 쓰기 문구.
 */

import type { KnownCommand } from "../server/commands";

const READ_FAILURE_REPLY = "일시적인 오류가 생겼어요. 잠시 후 다시 쳐 주세요.";
const WRITE_FAILURE_REPLY =
  "오류가 생겼어요. 처리됐을 수도 있으니 확인한 뒤 다시 쳐 주세요.";

/**
 * 다시 쳐도 **아무것도 바뀌지 않는** 명령. `runCommand` 의 `case` 이름 그대로 적는다.
 *
 * ★ **허용 목록이다.** 여기 없는 이름은 전부 쓰기 문구로 떨어진다 — 새 명령을 여기 넣는 것을
 *   잊어도 "확인하고 다시 치라"는 안전한 쪽으로 틀린다. 쓰기 명령(`연결` · `연결해제` · `드랍` ·
 *   `드롭` · `보스`)을 따로 적지 않는 이유도 같다. 쓰기 명령을 여기에 넣으면 안 된다.
 * ★ `!숙제` · `!검마` · `!결정석` 은 읽기가 아니다 — 넥슨 갱신이 원장에 클리어를 넣고 같은 보스의 다른
 *   난이도 행을 눕히기도 한다(`recordApiClears`). 그래도 여기 있는 이유는 다시 쳐도 안전해서다. 사람이 친
 *   값이 아니라 넥슨 관측을 옮기는 일이라 같은 관측이면 결과가 같고(주차별 유니크 + 기존 행 갱신),
 *   5분 쿨다운이 두 번째 호출을 막는다.
 * ★ `!분배` 는 계산만 한다(`!분배 취소` 도 지울 것이 없다고 답할 뿐이다). `!드랍` 과 다르다.
 */
const READ_ONLY_COMMANDS: ReadonlySet<string> = new Set<KnownCommand>([
  "도움말",
  "명령어",
  "help",
  "일정",
  "결정석",
  "결정패치",
  "검마",
  "검은마법사",
  "숙제",
  "분배",
  "환산",
  "웹",
  "사이트",
  "파티",
]);

/** `name` 은 `ParsedCommand.name` 이다(`!` 를 뗀 소문자). */
export function commandFailureReply(name: string): string {
  return READ_ONLY_COMMANDS.has(name) ? READ_FAILURE_REPLY : WRITE_FAILURE_REPLY;
}
