"use client";

/**
 * 넥슨 호출 **발사 간격 조절기** (클라이언트 측).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 왜 필요한가 — 실측으로 확인된 결함
 * ─────────────────────────────────────────────────────────────────────────────
 * 캐릭터 선택 모달은 보이는 12명의 초상화를 **캐릭터당 1콜**로 받는다(§2.1.1).
 * 그런데 카드마다 `useQuery` 가 하나씩 달려 있어 모달을 여는 순간 **12건이 동시에**
 * 나간다. 개발 키의 한도는 하루 1,000콜이면서 동시에 **초당 5콜**이다(§1.1).
 *
 * 실측(2026-08-17, 로컬 프로덕션 빌드): 12건 동시 발사 → **7건이 429**.
 * 게다가 `lib/nexon/gateway.ts` 는 429 를 한 번 받으면 그 키를 **60초 쿨다운**에
 * 넣으므로(`NEXON_RATE_LIMIT_COOLDOWN_MS`), 초상화 하나 때문에 **그 사용자의 모든
 * 넥슨 호출이 1분간 막힌다** — 직후의 로그인·스케줄러 동기화까지 함께 죽는다.
 * 즉 손해가 "초상화 몇 장 실루엣"에서 끝나지 않는다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 무엇을 하는가
 * ─────────────────────────────────────────────────────────────────────────────
 * 통과하는 요청의 **시작 시점**을 최소 간격만큼 벌린다. 완료를 기다리지 않으므로
 * (동시 실행 자체는 허용) 느린 응답 하나가 뒤의 전부를 붙잡지 않는다.
 *
 * ⚠️ **최선의 방어선은 아니다.** 진짜 자리는 서버의 `lib/nexon/gateway.ts` 다 —
 *    거기서 막아야 봇·서버 동기화 같은 다른 호출 경로까지 함께 보호된다.
 *    이 모듈은 브라우저에서 출발하는 버스트만 막는다. 탭을 여러 개 열면 각 탭이
 *    자기 몫으로 간격을 벌리므로 합산 속도는 다시 한도를 넘을 수 있다.
 *
 * ⚠️ 간격은 **개발 키(5콜/초)** 기준이다. 서비스 키는 500콜/초라 이 간격이 오히려
 *    병목이 된다. 키를 승격하면 여기를 함께 고친다.
 */

/**
 * 호출 시작 사이의 최소 간격.
 *
 * 개발 키 한도가 초당 5콜이므로 200ms 면 딱 한도다. 딱 맞추면 네트워크 지터로
 * 넘어가므로 **250ms(초당 4콜)** 로 여유를 둔다. 12건이면 발사에 약 3초가 걸리고,
 * 그동안 카드는 실루엣을 보여 준다 — 실루엣은 정상 상태이지 에러가 아니다(§2.1.1).
 */
const MIN_START_INTERVAL_MS = 250;

/**
 * 직전 발사 시각. 모듈 전역인 것이 핵심이다 — 컴포넌트 12개가 각자 상태를 들면
 * 서로를 못 보고 결국 동시에 나간다.
 */
let lastStartedAt = 0;

/** 발사 순서를 직렬화하는 사슬. 각 요청은 앞 요청의 "발사 완료"만 기다린다. */
let startChain: Promise<void> = Promise.resolve();

function delay(ms: number): Promise<void> {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

/**
 * `run` 을 간격 제한에 맞춰 실행한다. 반환값과 예외는 `run` 의 것을 그대로 전달한다.
 *
 * ```ts
 * queryFn: () => paceNexonRequest(() => getNexonCharacterBasic(apiKey, ocid))
 * ```
 */
export function paceNexonRequest<T>(run: () => Promise<T>): Promise<T> {
  const slot = startChain.then(async () => {
    const waitMs = lastStartedAt + MIN_START_INTERVAL_MS - Date.now();
    if (waitMs > 0) await delay(waitMs);
    lastStartedAt = Date.now();
  });

  // 사슬에는 **실패를 흘리지 않는다.** 한 요청이 던졌다고 뒤의 요청까지 막히면
  // 화면이 통째로 멈춘다.
  startChain = slot.then(
    () => undefined,
    () => undefined,
  );

  return slot.then(run);
}

/** 테스트·수동 검증용. 간격 상태를 초기화한다. */
export function resetNexonPacer(): void {
  lastStartedAt = 0;
  startChain = Promise.resolve();
}
