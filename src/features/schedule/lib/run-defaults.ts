/**
 * 일정 등록 폼의 기본값 — **화면이 소유하는 값**이다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ 진짜 기본값이 둘로 보이는 이유
 * ─────────────────────────────────────────────────────────────────────────────
 * `party_runs.duration_minutes` 의 **DB 기본값은 30** 이고 그대로 둔다(마이그레이션
 * 없음). 그 값은 "컬럼을 빼먹고 INSERT 했을 때"의 최후 방어선이지, 사용자가 보는
 * 기본값이 아니다. 우리 경로는 화면·API·서버 어디에도 `duration_minutes` 를 생략하는
 * 자리가 없으므로(`POST /api/schedule/parties/{id}/runs` 가 `durationMinutes` 를
 * **필수**로 받는다) DB 기본값은 실제로 쓰이지 않는다.
 *
 * **사람이 보는 기본값의 주인은 이 상수 하나다.** 발주자 지시(2026-08-18): *"보스당
 * 소요시간은 20분을 기본으로 잡아."* 파티 인원수에 따라 바꾸지 않는다 — 인원 연동은
 * 요구된 바 없고, 추측으로 조건을 만들면 나중에 설명할 수 없는 동작이 된다.
 *
 * 이 값은 **연속 배치 간격**이기도 하다. 서버(`createPartyRuns`)가 i 번째 보스를
 * `시작 + durationMinutes × i` 에 놓으므로 미리보기와 저장 결과가 같은 값을 써야 한다.
 * 그래서 시간표 등록 창과 `/boss-plans` 일정 모달이 **이 상수를 함께** 읽는다 —
 * 두 화면이 각자 30 을 적어 두었다가 한쪽만 고쳐지는 일이 실제로 있었다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ★ 2026-10-11 — 상수의 **집이 옮겨졌고**, 아래 문장 하나가 거짓이었다
 * ─────────────────────────────────────────────────────────────────────────────
 * 여기 적혀 있던 *"사용자가 폼에서 고친 값은 언제나 그대로 존중된다"* 는 **사실이 아니었다.**
 * 이 상수를 읽는 세 호출부(`timetable-run-dialog` · `plan-run-dialog` ·
 * `bot/server/commands`)가 전부 상수를 **그대로** 서버에 보냈고, 폼에는 그 값을 고칠 칸이
 * 아예 없었다. 주석이 약속한 기능이 코드에 없었던 것이다.
 *
 * 이제 고친 값이 실제로 존중된다. 다만 **존중되는 자리가 폼이 아니라 파티다** — 보스별
 * 소요 시간은 `party_bosses.duration_minutes` 에 저장되고(발주 지시 2026-10-11:
 * *"한번 수정되면 저장되어 항상 이용되도록"*), 서버가 등록 때 그 값을 읽어 보스마다 다른
 * 길이로 연달아 깐다. 그래서 이 상수는 **"그 파티가 그 보스에 대해 아무것도 정하지 않았을
 * 때"의 폴백**이다.
 *
 * ⚠️ 값의 주인은 이제 `@/lib/domain/run-grouping` 의 `DEFAULT_RUN_MINUTES` 다(환경 중립 —
 *    웹과 봇이 같은 값을 봐야 한다). 여기서는 화면이 쓰던 이름으로 **재수출**만 한다.
 *    두 이름이 같은 값인 것이 중요하므로 숫자를 다시 적지 않는다.
 */
export { DEFAULT_RUN_MINUTES as DEFAULT_DURATION_MINUTES } from "@/lib/domain/run-grouping";

