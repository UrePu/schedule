/**
 * ═════════════════════════════════════════════════════════════════════════════
 * 넥슨 점검 창 — **언제까지 기다리면 되는가**
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * 발주자 설명(2026-08-20): *"메이플 패치날짜가되면 패치 시간부터 오후 1~2시까지 패치함"*
 * 같은 날 실제 점검 안내: **정기점검 04:00 ~ 10:00 (6시간)**.
 *
 * 두 사실을 합치면 규칙은 이렇다.
 *
 *   · 정기 점검 → **오전 10시**에 끝난다
 *   · 패치가 있는 날 → **오후 1~2시**까지 이어진다
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ★ 패치날인지 **예측하지 않는다.** 반응할 뿐이다
 * ─────────────────────────────────────────────────────────────────────────────
 * 오늘이 패치날인지 알 방법이 우리에게 없다. 넥슨 공지 API(`/notice-update`)를 긁어 오는
 * 길이 있지만, 그건 점검 중에도 호출량을 쓰는 데다 공지 제목을 파싱해 날짜를 추정하는
 * 일이라 **틀리면 조용히 틀린다.**
 *
 * 그래서 예측 대신 **관측**한다. 점검 응답(`OPENAPI00010` / `00011`)을 실제로 받았을 때만
 * 점검으로 인정하고, 그때 "다음에 언제 다시 볼지"를 이 표로 정한다:
 *
 * | 점검을 관측한 시각(KST) | 다시 확인할 시각 | 왜                                  |
 * |-------------------------|------------------|-------------------------------------|
 * | 10시 이전               | 오늘 **10:00**   | 정기 점검이면 여기서 끝난다          |
 * | 10시 ~ 14시             | 오늘 **14:00**   | 아직 하는 걸 보니 패치날이다        |
 * | 14시 이후               | **30분 뒤**      | 예정 밖 점검 — 아는 게 없으니 짧게  |
 *
 * ⚠️ 이 값들은 **호출을 아끼기 위한 것**이지 약속이 아니다. 점검이 일찍 끝나면 그만큼
 *    늦게 알아차리는데, 그 대가는 사용자가 새로고침을 한 번 누르면 사라진다 —
 *    **수동 갱신은 이 대기를 무시한다.** 반대 방향의 실수(점검 중 계속 두드리기)는
 *    개발 키 하루 1,000콜을 통째로 태우므로 훨씬 비싸다.
 */

import { kstDayKey, kstMoment, minutesFromKstDay } from "./kst-wallclock";

/** 정기 점검이 끝나는 시각(KST). 2026-08-20 안내 실측: 04:00 ~ 10:00. */
export const MAINTENANCE_REGULAR_END_HOUR = 10;

/**
 * 패치가 있는 날 점검이 끝나는 시각(KST).
 *
 * 발주자는 *"오후 1~2시"* 라고 했다. **늦은 쪽(14시)을 쓴다** — 13시로 잡으면 13~14시
 * 사이에 다시 두드려 실패하고, 그 실패가 캐릭터 수만큼 곱해진다. 늦게 잡아 손해 보는
 * 것은 알아차림이 최대 1시간 늦는 것뿐이고 그마저 수동 갱신으로 없앨 수 있다.
 */
export const MAINTENANCE_PATCH_END_HOUR = 14;

/** 예정 밖 점검일 때의 재확인 간격. 아는 것이 없으므로 짧게 잡는다. */
const UNSCHEDULED_RECHECK_MS = 30 * 60 * 1000;

/**
 * 사용자에게 그대로 보여도 되는 **점검 일정 설명**.
 *
 * 문구를 여기 두는 이유는 화면·봇·에러 메시지가 같은 문장을 써야 하기 때문이다. 시각이
 * 각자 적혀 있으면 언젠가 한쪽만 고쳐진다.
 */
export const MAINTENANCE_SCHEDULE_NOTE =
  "정기 점검은 보통 오전 10시에 끝나고, 패치가 있는 날은 오후 1~2시까지 이어집니다.";

/**
 * 점검을 관측했다. **언제 다시 확인하면 되는가.**
 *
 * 순수 함수라 `now` 를 받아 시험할 수 있다. 어느 요일인지는 보지 않는다 — 점검을 실제로
 * 받은 뒤에만 불리므로 "오늘이 점검일인가"는 이미 답이 나와 있고, 목요일이 아닌 날의
 * 임시 점검도 같은 규칙으로 다루면 된다.
 */
export function nextMaintenanceRecheckAt(now: Date): Date {
  const dayKey = kstDayKey(now);
  const minutes = minutesFromKstDay(now, dayKey);

  if (minutes < MAINTENANCE_REGULAR_END_HOUR * 60) {
    return kstMoment(dayKey, MAINTENANCE_REGULAR_END_HOUR * 60);
  }
  if (minutes < MAINTENANCE_PATCH_END_HOUR * 60) {
    return kstMoment(dayKey, MAINTENANCE_PATCH_END_HOUR * 60);
  }
  return new Date(now.getTime() + UNSCHEDULED_RECHECK_MS);
}

/**
 * "10시쯤 끝납니다" 처럼 **사용자가 읽을 한 조각**.
 *
 * `nextMaintenanceRecheckAt` 과 **같은 분기**를 쓴다. 화면에 적힌 시각과 실제로 다시
 * 시도하는 시각이 어긋나면, 사용자는 우리가 말한 시각에 눌러 보고 또 실패한다.
 */
export function describeMaintenanceWait(now: Date): string {
  const minutes = minutesFromKstDay(now, kstDayKey(now));

  if (minutes < MAINTENANCE_REGULAR_END_HOUR * 60) {
    return `정기 점검이면 오전 ${String(MAINTENANCE_REGULAR_END_HOUR)}시쯤 끝납니다.`;
  }
  if (minutes < MAINTENANCE_PATCH_END_HOUR * 60) {
    // 10시가 지났는데도 점검 중이면 패치날로 본다. 추측이 아니라 관측에 근거한 판단이다.
    return `10시가 지나도 점검 중인 걸 보니 패치가 있는 날입니다. 오후 ${String(
      MAINTENANCE_PATCH_END_HOUR - 12,
    )}시쯤까지 이어집니다.`;
  }
  return "예정 밖 점검입니다. 30분 뒤에 다시 확인합니다.";
}
