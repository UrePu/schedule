/**
 * ═════════════════════════════════════════════════════════════════════════════
 * 넥슨 점검 창 — **API 는 게임보다 늦게 돌아온다**
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ★ 첫 구현이 틀렸다. 무엇을 잘못 알았나
 * ─────────────────────────────────────────────────────────────────────────────
 * 처음에는 이렇게 짰다: *"정기 점검은 10시에 끝난다. 10시가 지나도 점검이면 패치날이니
 * 2시까지."* 발주자가 바로 정정했다(2026-08-20):
 *
 *   *"정기점검이 아니라.. 점검이 있는날에 패치는 10시에 끝나지만 API 는 보통
 *     1시~2시까지 보인다고"*
 *
 * 즉 **10시는 게임이 열리는 시각이지 API 가 돌아오는 시각이 아니다.** 점검이 있는 날이면
 * (정기든 패치든) 넥슨 오픈 API 는 그 뒤로도 **세 시간 남짓 더** 닫혀 있다.
 *
 * 이 차이가 왜 중요한가:
 *
 *   · 10시에 다시 시도하도록 짜 두면 **거의 확실히 실패한다.** 그 실패가 추적 캐릭터
 *     수만큼 곱해지고, 사용자는 10시부터 1시까지 세 시간 동안 계속 실패를 본다.
 *   · 더 나쁜 것은 **문구**다. "10시쯤 끝납니다"라고 말해 놓고 10시에 안 되면, 그 뒤로는
 *     우리 안내를 아무도 믿지 않는다.
 *   · 반대로 사용자가 겪는 진짜 혼란은 **"게임은 되는데 왜 앱은 안 되지?"** 이고,
 *     그 답을 우리가 알고 있다. 말해 주면 된다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 그래서 이렇게 기다린다
 * ─────────────────────────────────────────────────────────────────────────────
 * | 점검을 관측한 시각(KST) | 다시 확인할 시각 | 왜                                   |
 * |-------------------------|------------------|--------------------------------------|
 * | 13시 이전               | 오늘 **13:00**   | API 복구의 **이른 쪽**. 여기서 되면 끝 |
 * | 13시 ~ 14시             | 오늘 **14:00**   | 13시에 아직이면 늦은 쪽까지 기다린다   |
 * | 14시 이후               | **30분 뒤**      | 예정 밖 — 아는 게 없으니 짧게          |
 *
 * ★ **1~2시를 한 번에 2시로 접지 않는다.** 13시에 한 번 찔러 보는 비용은 **호출 1회**다
 *   (자동 동기화는 첫 점검 응답에서 배치를 끊으므로 캐릭터 수만큼 늘지 않는다). 그 1회로
 *   흔한 경우에 한 시간 일찍 복구된다 — 값이 맞는 거래다.
 *
 * ⚠️ 이 값들은 **호출을 아끼기 위한 것**이지 약속이 아니다. 점검이 일찍 끝나면 그만큼
 *    늦게 알아차리는데, 그 대가는 사용자가 새로고침을 한 번 누르면 사라진다 —
 *    **수동 갱신은 이 대기를 무시한다.** 반대 방향의 실수(점검 중 계속 두드리기)는
 *    개발 키 하루 1,000콜을 통째로 태우므로 훨씬 비싸다.
 */

import { kstDayKey, kstMoment, minutesFromKstDay } from "./kst-wallclock";

/**
 * **게임**이 열리는 시각(KST). 2026-08-20 점검 안내 실측: 04:00 ~ 10:00.
 *
 * ⚠️ 이 값으로 재시도 시각을 정하면 안 된다. 우리가 부르는 것은 게임이 아니라 API 이고,
 *    API 는 이보다 세 시간쯤 늦게 돌아온다. 이 상수는 **문구에서만** 쓰인다 —
 *    "게임은 열렸는데 왜 앱은 안 되냐"에 답하기 위해서다.
 */
export const GAME_MAINTENANCE_END_HOUR = 10;

/** 넥슨 API 가 돌아오는 **이른 쪽**(발주자: *"보통 1시~2시"*). 여기서 한 번 찔러 본다. */
export const API_RECOVERY_EARLY_HOUR = 13;

/** 넥슨 API 가 돌아오는 **늦은 쪽**. 여기까지도 안 되면 예정 밖 점검으로 다룬다. */
export const API_RECOVERY_LATE_HOUR = 14;

/** 예정 밖 점검일 때의 재확인 간격. 아는 것이 없으므로 짧게 잡는다. */
const UNSCHEDULED_RECHECK_MS = 30 * 60 * 1000;

/**
 * 사용자에게 그대로 보여도 되는 **점검 일정 설명**.
 *
 * 문구를 여기 두는 이유는 화면·봇·에러 메시지가 같은 문장을 써야 하기 때문이다. 시각이
 * 각자 적혀 있으면 언젠가 한쪽만 고쳐진다.
 */
export const MAINTENANCE_SCHEDULE_NOTE =
  "점검이 있는 날에는 게임이 오전 10시에 열려도 넥슨 API 는 보통 오후 1~2시에야 돌아옵니다.";

/**
 * 점검을 관측했다. **언제 다시 확인하면 되는가.**
 *
 * 순수 함수라 `now` 를 받아 시험할 수 있다. 어느 요일인지는 보지 않는다 — 점검을 실제로
 * 받은 뒤에만 불리므로 "오늘이 점검일인가"는 이미 답이 나와 있고, 목요일이 아닌 날의
 * 임시 점검도 같은 규칙으로 다루면 된다.
 */
export function nextMaintenanceRecheckAt(now: Date): Date {
  const dayKey = kstDayKey(now);
  const minutes = minutesFromKstDay(now, dayKey);

  if (minutes < API_RECOVERY_EARLY_HOUR * 60) {
    return kstMoment(dayKey, API_RECOVERY_EARLY_HOUR * 60);
  }
  if (minutes < API_RECOVERY_LATE_HOUR * 60) {
    return kstMoment(dayKey, API_RECOVERY_LATE_HOUR * 60);
  }
  return new Date(now.getTime() + UNSCHEDULED_RECHECK_MS);
}

/**
 * 사용자가 읽을 한 조각. **`nextMaintenanceRecheckAt` 과 같은 분기를 쓴다** — 화면에 적힌
 * 시각과 실제로 다시 시도하는 시각이 어긋나면, 사용자는 우리가 말한 시각에 눌러 보고
 * 또 실패한다.
 *
 * 10시 이후 문구가 따로 있는 이유: 그때부터 사용자는 **게임에 접속할 수 있다.** 그래서
 * "왜 게임은 되는데 여기는 안 되지"가 생기고, 그 답을 먼저 말해 줘야 한다.
 */
export function describeMaintenanceWait(now: Date): string {
  const minutes = minutesFromKstDay(now, kstDayKey(now));

  if (minutes < GAME_MAINTENANCE_END_HOUR * 60) {
    return `게임 점검은 오전 ${String(GAME_MAINTENANCE_END_HOUR)}시에 끝나지만, 넥슨 API 는 보통 오후 1~2시에야 돌아옵니다.`;
  }
  if (minutes < API_RECOVERY_EARLY_HOUR * 60) {
    return "게임은 열렸지만 넥슨 API 는 아직 점검 중입니다. 보통 오후 1~2시에 돌아옵니다.";
  }
  if (minutes < API_RECOVERY_LATE_HOUR * 60) {
    return `넥슨 API 가 돌아올 시간대입니다. 오후 ${String(
      API_RECOVERY_LATE_HOUR - 12,
    )}시까지는 대체로 복구됩니다.`;
  }
  return "예정 밖 점검입니다. 30분 뒤에 다시 확인합니다.";
}
