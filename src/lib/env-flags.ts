/**
 * 빌드/실행 환경 플래그. **개발 편의 기능의 게이트는 전부 여기를 경유한다.**
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * `process.env.NODE_ENV !== "production"` 를 쓰지 않는 이유
 * ─────────────────────────────────────────────────────────────────────────────
 * 실제로 개발용 계측이 프로덕션 HTML 로 새어 나간 적이 있다. 원인은 두 겹이다.
 *
 * 1. **부정 비교는 fail-open 이다.** `!== "production"` 은 `NODE_ENV` 가 비어 있거나
 *    `"test"` / `"staging"` 이면 **참**이 된다. 즉 "모르면 켠다"이고, 이건
 *    노출 방향으로 실패한다. 게이트는 언제나 "모르면 끈다"여야 한다.
 *
 * 2. **`NODE_ENV` 는 빌드 시점에 상수로 박힌다.** Next 가 클라이언트·서버 번들
 *    양쪽에서 이 표현식을 인라인하므로, 빌드를 잘못된 `NODE_ENV` 로 돌리면
 *    그 값이 **배포물에 그대로 굳는다.** 런타임에 `NODE_ENV=production` 으로
 *    실행해도 되돌릴 수 없다. 그래서 `=== "development"` 로 fail-closed 하게
 *    바꾸는 것만으로는 부족하다 — 빌드 환경이 오염되면 똑같이 샌다.
 *
 * → 그래서 **화면에 보이는 개발 도구는 별도의 명시적 플래그**로 켠다.
 *   프로덕션은 그 변수를 **설정하지 않으면 그만**이고, 잊어버려도 꺼진 채로 남는다.
 *   `NODE_ENV` 가 무엇이든 영향을 받지 않는다.
 */

/**
 * 화면에 보이는 개발 도구(계측 표시, 실패 주입 토글 등)를 켤지 여부.
 *
 * **명시적 옵트인이다.** 켜려면 `.env.local` 에 `NEXT_PUBLIC_DEV_TOOLS=1` 을 넣는다
 * (`.env.local.example` 참고). 프로덕션 배포는 이 변수를 설정하지 않는다.
 *
 * ⚠️ 사용자에게 보이는 개발용 UI 는 **반드시 이 플래그**로 감쌀 것.
 *    `NODE_ENV` 로 직접 가르지 말 것 — 위 2번 이유 때문에 배포물에 굳어 버린다.
 */
export const IS_DEV_TOOLS_ENABLED = process.env.NEXT_PUBLIC_DEV_TOOLS === "1";

/**
 * 순수 개발 편의 **동작**(목 데이터의 인위적 지연, 잘못된 설정에 대한 즉시 throw 등).
 * 화면에 문자열을 남기지 않는 것들만 여기에 걸린다.
 *
 * 긍정 비교라 `NODE_ENV` 가 비었거나 `"test"` 여도 **꺼진다**(fail-closed).
 */
export const IS_DEVELOPMENT = process.env.NODE_ENV === "development";
