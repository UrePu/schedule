/**
 * ═════════════════════════════════════════════════════════════════════════════
 * 페이지 셸 — 최대 폭과 반응형 여백의 **단일 출처**
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * 예전에는 `PAGE_SHELL_CLASS` 가 `/`, `/income`, `/boss-plans` 세 파일에 **각각**
 * 복사돼 있었고 `/schedule` 과 `/showcase` 는 또 다른 문자열을 직접 썼다.
 * 그 결과 규칙이 조용히 갈라져 있었다:
 *   - 좁은 폭 3종은 `md:px-6` 이 **빠져 있어** 1440px 화면에서도 좌우 여백이 16px 이었다.
 *   - `/schedule` 만 `md:px-6` 이 있었고, `/showcase` 만 `lg:` 단계가 하나 더 있었다.
 * 이제 이 파일이 유일한 정의이며, 페이지는 어느 폭 계열을 쓸지만 고른다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 왜 폭이 두 가지인가
 * ─────────────────────────────────────────────────────────────────────────────
 * - `PAGE_SHELL_CLASS` (max-w-6xl, 72rem) — 읽는 화면. 카드와 문장이 주인공이라
 *   한 줄이 너무 길어지면 오히려 읽기 어렵다.
 * - `WIDE_PAGE_SHELL_CLASS` (max-w-[92rem]) — `/schedule` 처럼 **가로 폭이 곧
 *   정보량**인 화면. 겹쳐보기 시간표는 폭을 깎는 순간 시간축이 뭉갠다(§1.4).
 *   상단 바 컨테이너와 같은 폭이라 두 줄의 좌우 끝이 정확히 맞는다.
 *
 * 공통 규칙(둘 다 지킨다):
 *   - 좌우 여백 16px → 768px 이상에서 24px. **360px 에서 본문 폭 328px** 이 나온다.
 *   - 세로 여백은 `section-mobile`(24px) → `section-tablet`(40px).
 *   - `w-full` + `mx-auto` 로 가운데 정렬. `min-w-0` 는 각 페이지 내부 요소가 맡는다.
 */

/** 공통 뼈대 — 폭 상한과 세로 간격만 계열별로 다르다. */
const SHELL_BASE =
  "mx-auto flex w-full flex-col px-4 py-section-mobile md:px-6 md:py-section-tablet";

/** 기본 셸. 이번 주 일정 · 숙제 · 보스 계획 · 수익 · 드랍 · 기타 · 쇼케이스가 쓴다. */
export const PAGE_SHELL_CLASS = `${SHELL_BASE} max-w-6xl gap-section-mobile md:gap-section-tablet`;

/**
 * 넓은 셸. 현재 사용처는 **`/schedule` · `/parties` · `/boss-status`** 다.
 * (2026-09-04 이전 이 주석은 "`/schedule` 전용"이라고 단언했는데, 그때 이미
 *  `/parties` 가 함께 쓰고 있었다. 사용처를 단언하려면 사실이어야 한다.)
 *
 * 세로 간격이 `gap-4`(16px)로 더 촘촘한 이유: `/schedule` 은 파티 바 → 겹쳐보기 →
 * 등록 폼이 **하나의 작업 흐름**이라 섹션 사이를 40px 씩 벌리면 시선이 끊긴다.
 *
 * ⚠️ 그 근거는 **폭이 아니라 흐름**에서 나온다. 그래서 폭만 필요하고 흐름은 아닌
 *    화면 — `/boss-status`(2026-09-04, 카드 가로 확장) — 은 이 상수를 그대로 쓰되
 *    페이지에서 `cn()` 으로 `gap-section-*` 을 덧써 되돌린다. 세 번째 셸 상수를
 *    만들지 않는 이유는 이 파일 머리말과 같다: 폭 규칙의 출처는 하나여야 한다.
 */
export const WIDE_PAGE_SHELL_CLASS = `${SHELL_BASE} max-w-[92rem] gap-4`;
